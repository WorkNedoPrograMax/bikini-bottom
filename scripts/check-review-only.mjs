// Checks the review-only guard (Karen never changes code) against dist/, with
// plain node. Run after `npm run build`:  node scripts/check-review-only.mjs
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { isReviewOnlyAllowed, REVIEW_ONLY_REASON, REVIEW_ONLY_NOTE } = require("../dist/main/domain/reviewOnly.js");
const { visibleOnStreet } = require("../dist/main/domain/snapshot.js");

let fails = 0;
const ok = (cond, msg) => { if (!cond) { fails++; console.log("  ✗", msg); } else console.log("  ✓", msg); };
const bash = (command) => isReviewOnlyAllowed("Bash", { command });

console.log("review-only — allowed (the review itself and everything it needs):");
ok(isReviewOnlyAllowed("Read", { file_path: "lib/main.dart" }), "Read");
ok(isReviewOnlyAllowed("Grep", { pattern: "x" }), "Grep");
ok(isReviewOnlyAllowed("mcp__bikini__ask_maksym", { story: "s" }), "ask_maksym");
ok(isReviewOnlyAllowed("mcp__bikini__post_status", { text: "s" }), "post_status");
ok(isReviewOnlyAllowed("Agent", { prompt: "review this", subagent_type: "hc-reviewer" }), "a helper (its own calls pass this hook too)");
ok(bash("git fetch origin && git switch dev && git pull --ff-only"), "git fetch / switch dev / pull --ff-only");
ok(bash("gh pr checkout 123 -R EmpatDevelopment/highcap-mobile"), "gh pr checkout");
ok(bash("gh pr view 123 --json files,reviews && gh pr diff 123"), "gh pr view / diff");
ok(bash("gh pr checks 123 -R org/repo"), "gh pr checks");
ok(bash("git diff origin/dev...HEAD --stat | head -50"), "git diff … | head");
ok(bash("git log --oneline -20 && git status --porcelain"), "git log / status");
ok(bash("git branch --show-current"), "git branch --show-current");
ok(bash("fvm flutter analyze && fvm flutter test"), "fvm flutter analyze / test");
ok(bash("fvm dart run build_runner build --delete-conflicting-outputs"), "build_runner (generated code, never source)");
ok(bash("fvm dart format --set-exit-if-changed lib"), "dart format --set-exit-if-changed (a check)");
ok(bash("python3 ~/.claude/scripts/hc-precedents.py --diff origin/dev...HEAD"), "the precedent selector");
ok(bash("gh pr review 123 -R org/repo --approve -b 'Looks right.'"), "gh pr review --approve");
ok(bash("gh pr review 123 -R org/repo --request-changes -b \"$(cat <<'EOF'\nverdict\nEOF\n)\""), "gh pr review --request-changes with a heredoc body");
ok(bash("gh pr comment 123 -R org/repo -b 'one note'"), "gh pr comment");
ok(bash("gh pr edit 123 -R org/repo --add-reviewer anna"), "gh pr edit --add-reviewer (ask to look again)");
ok(bash("gh api repos/org/repo/pulls/123/comments"), "gh api (GET)");
ok(bash("cat lib/x.dart | grep -n foo"), "cat | grep");
ok(bash("sed -n 1,40p lib/x.dart"), "sed -n (reads)");
ok(bash("ls -la 2>&1 | head"), "2>&1 is not a file write");
ok(bash("fvm flutter test > /dev/null 2>&1; echo $?"), "> /dev/null is not a file write");
ok(bash("git switch dev"), "git switch dev (back on the main line)");
ok(isReviewOnlyAllowed("mcp__claude_ai_Atlassian_MCP__getJiraIssue", { key: "HIGHCAP-1" }), "a read-shaped connector tool");

console.log("review-only — refused (changes code, git, or GitHub):");
ok(!isReviewOnlyAllowed("Edit", { file_path: "lib/main.dart", old_string: "a", new_string: "b" }), "Edit");
ok(!isReviewOnlyAllowed("Write", { file_path: "README.md", content: "x" }), "Write");
ok(!isReviewOnlyAllowed("MultiEdit", { file_path: "x" }), "MultiEdit");
ok(!isReviewOnlyAllowed("NotebookEdit", { notebook_path: "x" }), "NotebookEdit");
ok(!isReviewOnlyAllowed("EnterWorktree", {}), "EnterWorktree");
ok(!isReviewOnlyAllowed("Agent", { prompt: "x", isolation: "worktree" }), "a worktree-isolated helper");
ok(!bash("git add -A && git commit -m 'fix'"), "git add / commit");
ok(!bash("git commit --amend --no-edit"), "git commit --amend");
ok(!bash("git push origin HEAD"), "git push");
ok(!bash("git push --force-with-lease"), "git push --force-with-lease");
ok(!bash("git reset --hard origin/dev"), "git reset --hard");
ok(!bash("git rebase origin/dev"), "git rebase");
ok(!bash("git merge dev"), "git merge");
ok(!bash("git cherry-pick abc123"), "git cherry-pick");
ok(!bash("git stash"), "git stash (push)");
ok(!bash("git restore lib/x.dart"), "git restore (a file change, even an undo)");
ok(!bash("git checkout -- lib/x.dart"), "git checkout -- <file>");
ok(!bash("git switch -c fix/thing"), "git switch -c (creates a branch)");
ok(!bash("git checkout -b fix/thing"), "git checkout -b");
ok(!bash("git branch -D old"), "git branch -D");
ok(!bash("git branch fix/thing"), "git branch <name> (creates one)");
ok(!bash("git tag v1"), "git tag <name>");
ok(!bash("git worktree add ../x"), "git worktree add");
ok(!bash("git clean -fd"), "git clean -fd");
ok(!bash("git -C /repo push"), "git -C <dir> push");
ok(!bash("gh pr create --title x --body y"), "gh pr create");
ok(!bash("gh pr merge 123 --squash"), "gh pr merge");
ok(!bash("gh pr close 123"), "gh pr close");
ok(!bash("gh pr ready 123"), "gh pr ready");
ok(!bash("gh pr edit 123 --title 'new'"), "gh pr edit --title");
ok(!bash("gh pr edit 123 --add-reviewer anna --body 'x'"), "gh pr edit --add-reviewer AND --body");
ok(!bash("gh api -X PATCH repos/o/r/pulls/1 -f title=x"), "gh api -X PATCH");
ok(!bash("gh api repos/o/r/pulls/1/merge --method PUT"), "gh api --method PUT");
ok(!bash("gh repo delete o/r"), "gh repo delete");
ok(!bash("echo 'x' > lib/x.dart"), "echo > file");
ok(!bash("cat a >> b"), "cat >> file");
ok(!bash("fvm flutter analyze && echo ok > report.txt"), "a write hidden after && ");
ok(!bash("gh pr diff 1 | tee out.diff"), "tee (writes a file)");
ok(!bash("sed -i '' 's/a/b/' lib/x.dart"), "sed -i");
ok(!bash("rm -rf build"), "rm");
ok(!bash("mv a b"), "mv");
ok(!bash("cp a b"), "cp");
ok(!bash("touch x"), "touch");
ok(!bash("mkdir -p x"), "mkdir");
ok(!bash("python3 -c \"open('x','w').write('y')\""), "python3 -c (unparseable → refused)");
ok(!bash("node -e \"require('fs').writeFileSync('x','y')\""), "node -e");
ok(!bash("python3 fix.py"), "python3 <a script that is not the library's>");
ok(!bash("fvm dart fix --apply"), "dart fix --apply");
ok(!bash("fvm dart format lib"), "dart format (rewrites files)");
ok(!bash("npm run deploy"), "npm run deploy");
ok(!bash("npx something"), "npx (unknown)");
ok(!bash("curl -X POST https://x"), "curl (unknown)");
ok(!bash("some-unknown-tool --flag"), "an unknown command");
ok(!bash("claude --worktree x -p hi"), "claude --worktree");
ok(!isReviewOnlyAllowed("mcp__claude_ai_Atlassian_MCP__editJiraIssue", {}), "a write-shaped connector tool");
ok(!isReviewOnlyAllowed("mcp__claude_ai_Atlassian_MCP__transitionJiraIssue", {}), "transitionJiraIssue");
ok(!isReviewOnlyAllowed("mcp__claude_ai_Slack__slack_send_message", {}), "slack_send_message");

console.log("review-only — the words:");
ok(/never changes code/.test(REVIEW_ONLY_REASON) && /author fixes it/.test(REVIEW_ONLY_REASON), "the refusal says who fixes it");
ok(/git switch dev/.test(REVIEW_ONLY_NOTE) && /gh pr review/.test(REVIEW_ONLY_NOTE), "the prompt line names the deliverable and the way back to dev");

console.log("street — the reviewer is visible only while reviewing:");
ok(visibleOnStreet({ reviewer: false, state: "idle", unseen: false }), "a builder idle → visible");
ok(!visibleOnStreet({ reviewer: true, state: "idle", unseen: false }), "the reviewer idle, nothing unseen → hidden");
ok(visibleOnStreet({ reviewer: true, state: "working", unseen: false }), "the reviewer working → visible");
ok(visibleOnStreet({ reviewer: true, state: "calling", unseen: true }), "the reviewer asking 'what do I post?' → visible");
ok(visibleOnStreet({ reviewer: true, state: "idle", unseen: true }), "the reviewer done but not yet opened → still visible");

console.log(fails ? `\n${fails} check(s) failed` : "\nall review-only checks passed");
process.exit(fails ? 1 : 0);
